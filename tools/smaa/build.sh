#!/bin/bash
# Compiles the SMAA compute shaders to SPIR-V for ci/fw-files/src/graphics/vulkan/mp3_smaa_shaders.h
# (glslangValidator, Ubuntu's glslang-tools). Run it after changing a shader; the header is committed.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../ci/fw-files/src/graphics/vulkan/mp3_smaa_shaders.h"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
for pass in edges weights blend; do
  name="kMp3Smaa${pass^}Cs"
  glslangValidator -V --target-env vulkan1.0 -I"$here" -o "$tmp/$pass.spv" "$here/smaa_$pass.comp"
  spirv-val --target-env vulkan1.0 "$tmp/$pass.spv"
  glslangValidator -V --target-env vulkan1.0 -I"$here" --vn "$name" -o "$tmp/$pass.h" "$here/smaa_$pass.comp"
done
{
  echo "// Generated by tools/smaa/build.sh from tools/smaa/*.comp (SMAA: MIT, tools/smaa/LICENSE.txt)."
  echo "#pragma once"
  echo "#include <cstdint>"
  for pass in edges weights blend; do grep -v "^#pragma once\|^ *//" "$tmp/$pass.h"; done
} > "$out"
echo "wrote $out"
